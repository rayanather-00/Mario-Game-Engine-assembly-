OLD_KEYBOARD_ISR  DW 0, 0

INSTALL_KEYBOARD:
    PUSH AX
    PUSH DX
    PUSH DS
    ; SAVE OLD KEYBOARD INTERRUPT
    MOV AX, 3509H
    INT 21H
    MOV [OLD_KEYBOARD_ISR], BX
    MOV [OLD_KEYBOARD_ISR+2], ES
    ; INSTALL OUR KEYBOARD INTERRUPT
    PUSH CS
    POP DS
    MOV DX, KEYBOARD_ISR
    MOV AX, 2509H
    INT 21H

    POP DS
    POP DX
    POP AX
    RET

; interuupt handling 
KEYBOARD_ISR:
    PUSH AX
    PUSH BX
    PUSH DS
    PUSH CS
    POP DS

    IN AL, 60H ; READ KEYBOARD SCAN CODE
    MOV BL, AL
    ; CHECK PRESS OR RELEASE
    AND AL, 7FH
    MOV BH, AL
    CMP BL, 80H
    JB KEY_PRESSED

KEY_RELEASED:
    CMP BH, 4BH
    JE RELEASE_LEFT

    CMP BH, 4DH
    JE RELEASE_RIGHT

    CMP BH, 2AH
    JE RELEASE_SHIFT

    CMP BH, 36H
    JE RELEASE_SHIFT

    CMP BH, 39H
    JE RELEASE_SPACE

    CMP BH, 01H
    JE RELEASE_ESC

    JMP KEYBOARD_END


RELEASE_LEFT:
    MOV BYTE [LEFT_KEY], 0
    JMP KEYBOARD_END

RELEASE_RIGHT:
    MOV BYTE [RIGHT_KEY], 0
    JMP KEYBOARD_END

RELEASE_SHIFT:
    MOV BYTE [SHIFT_KEY], 0
    JMP KEYBOARD_END

RELEASE_SPACE:
    MOV BYTE [SPACE_KEY], 0
    JMP KEYBOARD_END

KEY_PRESSED:
    CMP BH, 4BH
    JE PRESS_LEFT

    CMP BH, 4DH
    JE PRESS_RIGHT

    CMP BH, 2AH
    JE PRESS_SHIFT

    CMP BH, 36H
    JE PRESS_SHIFT

    CMP BH, 39H
    JE PRESS_SPACE

    CMP BH, 01H
    JE PRESS_ESC

    JMP KEYBOARD_END


PRESS_LEFT:
    MOV BYTE [LEFT_KEY], 1
    JMP KEYBOARD_END

PRESS_RIGHT:
    MOV BYTE [RIGHT_KEY], 1
    JMP KEYBOARD_END

PRESS_SHIFT:
    MOV BYTE [SHIFT_KEY], 1
    JMP KEYBOARD_END

PRESS_SPACE:
    MOV BYTE [SPACE_KEY], 1
    JMP KEYBOARD_END

RELEASE_ESC:
    MOV BYTE [ESC_KEY], 0
    JMP KEYBOARD_END

PRESS_ESC:
    MOV BYTE [ESC_KEY], 1
    JMP KEYBOARD_END

KEYBOARD_END: 
    IN AL, 61H ; ACKNOWLEDGE KEYBOARD CONTROLLER
    MOV AH, AL
    OR AL, 80H
    OUT 61H, AL
    MOV AL, AH
    OUT 61H, AL

    ; SEND END OF INTERRUPT TO PIC
    MOV AL, 20H
    OUT 20H, AL
    POP DS
    POP BX
    POP AX
    IRET

; RESTORE ORIGINAL KEYBOARD INTERRUPT
UNINSTALL_KEYBOARD:
    PUSH AX
    PUSH DX
    PUSH DS

    MOV AX, [OLD_KEYBOARD_ISR]
    MOV DX, [OLD_KEYBOARD_ISR+2]
    MOV DS, DX

    MOV AX, 2509H
    MOV DX, [CS:OLD_KEYBOARD_ISR]
    INT 21H

    POP DS
    POP DX
    POP AX
    RET
