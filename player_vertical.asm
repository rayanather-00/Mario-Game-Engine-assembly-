START_JUMP:

    PUSH AX
    ; CHECK IF MARIO IS ON THE GROUND
    CMP BYTE [ON_GROUND], 1
    JNE END_START_JUMP

    ; CHECK IF SPACE IS PRESSED
    CMP BYTE [SPACE_KEY], 1
    JNE END_START_JUMP

    ; SET INITIAL JUMP VELOCITY
    MOV AX, JUMP_VELOCITY
    MOV [VELOCITY_Y], AX

    ; MARIO IS NOW AIRBORNE
    MOV BYTE [ON_GROUND], 0

    ; MARK JUMP AS HELD
    MOV BYTE [JUMP_HELDING], 1


END_START_JUMP:

    POP AX
    RET

;vertical moment
UPDATE_VERTICAL:
    PUSH AX
    ; CHECK IF MARIO IS AIRBORNE
    CMP BYTE [ON_GROUND], 1
    JE END_VERTICAL

    ; APPLY GRAVITY
    MOV AX, [VELOCITY_Y]
    ADD AX, GRAVITY

    ; CHECK MAXIMUM FALL SPEED
    CMP AX, MAX_FALL_SPEED
    JLE SAVE_VERTICAL_SPEED

    MOV AX, MAX_FALL_SPEED


SAVE_VERTICAL_SPEED:

    MOV [VELOCITY_Y], AX
; VARIABLE JUMP HEIGHT
    ; CHECK IF MARIO IS MOVING UPWARD
    CMP WORD [VELOCITY_Y], 0
    JGE END_VERTICAL

    ; CHECK IF SPACE IS STILL PRESSED
    CMP BYTE [SPACE_KEY], 1
    JE END_VERTICAL
    ; CHECK UPWARD SPEED CUTOFF
    CMP WORD [VELOCITY_Y], JUMP_CUTOFF
    JGE END_VERTICAL
    ; CUT THE JUMP SHORT
    MOV AX, JUMP_CUTOFF
    MOV [VELOCITY_Y], AX


END_VERTICAL:
    POP AX
    RET

; UPDATE MARIO POSITION

UPDATE_POSITION:
    PUSH AX
    ; UPDATE HORIZONTAL POSITION
    MOV AX, [MARIO_X]
    ADD AX, [VELOCITY_X]
    MOV [MARIO_X], AX
    ; UPDATE VERTICAL POSITION
    MOV AX, [MARIO_Y]
    ADD AX, [VELOCITY_Y]
    MOV [MARIO_Y], AX
    POP AX
    RET

; CHECK MARIO LEVEL BOUNDARIES
CHECK_BOUNDARIES:
    PUSH AX
    ; CHECK LEFT SCREEN EDGE
    CMP WORD [MARIO_X], 0000H
    JG CHECK_RIGHT_BOUNDARY
    ; STOP MARIO AT LEFT EDGE
    MOV WORD [MARIO_X], 0000H
    MOV WORD [VELOCITY_X], 0000H


CHECK_RIGHT_BOUNDARY:

    ; SCREEN WIDTH MINUS MARIO WIDTH
    MOV AX, SCREEN_WIDTH
    SUB AX, TILE_SIZE
    ; CHECK RIGHT SCREEN EDGE
    CMP WORD [MARIO_X], AX
    JL END_BOUNDARIES
    ; STOP MARIO AT RIGHT EDGE
    MOV [MARIO_X], AX
    MOV WORD [VELOCITY_X], 0000H


END_BOUNDARIES:
    POP AX
    RET

; UPDATE PLAYER MOVEMENT
UPDATE_PLAYER:
    PUSH AX
    ; CHECK IF MARIO IS ON THE GROUND
    CMP BYTE [ON_GROUND], 1
    JE GROUND_MOVEMENT
    ; MARIO IS IN THE AIR
    CALL AIR_CONTROL
    JMP END_PLAYER_MOVEMENT


GROUND_MOVEMENT:
    ; UPDATE HORIZONTAL MOVEMENT
    CALL UPDATE_HORIZONTAL


END_PLAYER_MOVEMENT:
    POP AX
    RET

; COMPLETE PLAYER UPDATE
UPDATE_PLAYER_FRAME:
    PUSH AX
    ; CHECK FOR JUMP INPUT
    CALL START_JUMP
    ; UPDATE HORIZONTAL MOVEMENT
    CALL UPDATE_PLAYER
    ; UPDATE VERTICAL MOVEMENT
    CALL UPDATE_VERTICAL
    ; UPDATE MARIO POSITION
    CALL UPDATE_POSITION
    ; CHECK SCREEN BOUNDARIES
    CALL CHECK_BOUNDARIES
    POP AX
    RET
