GET_SPEED_LIMIT:

    PUSH AX
    ; CHECK IF SHIFT IS PRESSED
    CMP BYTE [SHIFT_KEY], 1
    JE SET_RUN_SPEED
    ; USE WALKING SPEED
    MOV AX, MAX_WALK_SPEED
    JMP SAVE_SPEED_LIMIT

SET_RUN_SPEED:
    ; USE RUNNING SPEED
    MOV AX, MAX_RUN_SPEED


SAVE_SPEED_LIMIT:
    MOV [CURRENT_MAX_SPEED], AX
    POP AX
    RET


;keep trcak of speed limit
CHECK_LEFT_LIMIT:
    CALL GET_SPEED_LIMIT
    MOV AX, [VELOCITY_X]
    NEG AX
    CMP AX, [CURRENT_MAX_SPEED]
    JLE END_LEFT_LIMIT
    MOV AX, [CURRENT_MAX_SPEED]
    NEG AX
    MOV [VELOCITY_X], AX

END_LEFT_LIMIT:
    RET



; CHECK RIGHT SPEED LIMIT
CHECK_RIGHT_LIMIT:
    CALL GET_SPEED_LIMIT
    MOV AX, [VELOCITY_X]
    CMP AX, [CURRENT_MAX_SPEED]
    JLE END_RIGHT_LIMIT
    MOV AX, [CURRENT_MAX_SPEED]
    MOV [VELOCITY_X], AX
END_RIGHT_LIMIT:
    RET
