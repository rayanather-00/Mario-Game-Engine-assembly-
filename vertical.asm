START_JUMP:

    PUSH AX
    ; CHECK IF MARIO IS ON THE GROUND
    CMP BYTE [ON_GROUND], 1
    JNE END_START_JUMP

    ; CHECK IF SPACE IS PRESSED
    CMP BYTE [SPACE_KEY], 1
    JNE END_START_JUMP

    ; SET INITIAL JUMP VELOCITY
    MOV AX, JUMP_VELOCITY
    MOV [VELOCITY_Y], AX

    ; MARIO IS NOW AIRBORNE
    MOV BYTE [ON_GROUND], 0

    ; MARK JUMP AS HELD
    MOV BYTE [JUMP_HELDING], 1


END_START_JUMP:

    POP AX
    RET

;vertical moment
UPDATE_VERTICAL:
    PUSH AX
    ; CHECK IF MARIO IS AIRBORNE
    CMP BYTE [ON_GROUND], 1
    JE END_VERTICAL

    ; APPLY GRAVITY
    MOV AX, [VELOCITY_Y]
    ADD AX, GRAVITY

    ; CHECK MAXIMUM FALL SPEED
    CMP AX, MAX_FALL_SPEED
    JLE SAVE_VERTICAL_SPEED

    MOV AX, MAX_FALL_SPEED


SAVE_VERTICAL_SPEED:

    MOV [VELOCITY_Y], AX
; VARIABLE JUMP HEIGHT
    ; CHECK IF MARIO IS MOVING UPWARD
    CMP WORD [VELOCITY_Y], 0
    JGE END_VERTICAL

    ; CHECK IF SPACE IS STILL PRESSED
    CMP BYTE [SPACE_KEY], 1
    JE END_VERTICAL
    ; CHECK UPWARD SPEED CUTOFF
    CMP WORD [VELOCITY_Y], JUMP_CUTOFF
    JGE END_VERTICAL
    ; CUT THE JUMP SHORT
    MOV AX, JUMP_CUTOFF
    MOV [VELOCITY_Y], AX


END_VERTICAL:
    POP AX
    RET

; UPDATE MARIO POSITION

UPDATE_POSITION:
    PUSH AX

    ; UPDATE HORIZONTAL POSITION
    MOV AL,[VELOCITY_X]
    ADD [MARIO_X_FRAC],AL

    MOV AL,[VELOCITY_X+1]
    CBW
    ADC [MARIO_X],AX

    ; UPDATE VERTICAL POSITION
    MOV AL,[VELOCITY_Y]
    ADD [MARIO_Y_FRAC],AL

    MOV AL,[VELOCITY_Y+1]
    CBW
    ADC [MARIO_Y],AX

    POP AX
    RET

CHECK_SOLID_TILE:
    PUSH BP
    MOV BP,SP
    PUSH BX
    PUSH CX
    PUSH DX

    ; GET TILE ID
    PUSH WORD [BP+6]       ; X
    MOV AX,[BP+4]          ; Y
    SUB AX,8               ; MAP STARTS AT SCREEN Y=8
    PUSH AX
    CALL get_tile
    ADD SP,4

    ; CHECK SOLID TILE IDS
    CMP AL,1
    JE .SOLID
    CMP AL,2
    JE .SOLID
    CMP AL,4
    JE .SOLID
    CMP AL,5
    JE .SOLID
    CMP AL,6
    JE .SOLID
    CMP AL,7
    JE .SOLID
    CMP AL,8
    JE .SOLID
    CMP AL,10
    JE .SOLID

    MOV AL,0
    JMP .DONE

.SOLID:
    MOV AL,1

.DONE:
    POP DX
    POP CX
    POP BX
    POP BP
    RET

COLLIDE_HORIZONTAL:
    PUSH AX
    PUSH BX

    CMP WORD [VELOCITY_X],0
    JNE .CHECK_DIRECTION
    JMP .DONE

    .CHECK_DIRECTION:
    JL .CHECK_LEFT

    ; CHECK RIGHT SIDE
    MOV AX,[MARIO_X]
    ADD AX,15
    MOV BX,[MARIO_Y]
    INC BX

    PUSH AX
    PUSH BX
    CALL CHECK_SOLID_TILE
    ADD SP,4

    CMP AL,1
    JE .RIGHT_HIT

    MOV AX,[MARIO_X]
    ADD AX,15
    MOV BX,[MARIO_Y]
    ADD BX,14

    PUSH AX
    PUSH BX
    CALL CHECK_SOLID_TILE
    ADD SP,4

    CMP AL,1
    JNE .DONE

.RIGHT_HIT:
    MOV AX,[MARIO_X]
    ADD AX,15
    AND AX,0FFF0H
    SUB AX,16

    MOV [MARIO_X],AX
    MOV BYTE [MARIO_X_FRAC],0
    MOV WORD [VELOCITY_X],0
    JMP .DONE

.CHECK_LEFT:
    ; CHECK LEFT SIDE
    MOV AX,[MARIO_X]
    MOV BX,[MARIO_Y]
    INC BX

    PUSH AX
    PUSH BX
    CALL CHECK_SOLID_TILE
    ADD SP,4

    CMP AL,1
    JE .LEFT_HIT

    MOV AX,[MARIO_X]
    MOV BX,[MARIO_Y]
    ADD BX,14

    PUSH AX
    PUSH BX
    CALL CHECK_SOLID_TILE
    ADD SP,4

    CMP AL,1
    JNE .DONE

.LEFT_HIT:
    MOV AX,[MARIO_X]
    AND AX,0FFF0H
    ADD AX,16

    MOV [MARIO_X],AX
    MOV BYTE [MARIO_X_FRAC],0
    MOV WORD [VELOCITY_X],0

.DONE:
    POP BX
    POP AX
    RET

COLLIDE_VERTICAL:
    PUSH AX
    PUSH BX

    MOV BYTE [ON_GROUND],0

    CMP WORD [VELOCITY_Y],0
    JL .CHECK_UP

    ; CHECK BELOW MARIO
    MOV AX,[MARIO_X]
    INC AX
    MOV BX,[MARIO_Y]
    ADD BX,15

    PUSH AX
    PUSH BX
    CALL CHECK_SOLID_TILE
    ADD SP,4

    CMP AL,1
    JE .LAND

    MOV AX,[MARIO_X]
    ADD AX,14
    MOV BX,[MARIO_Y]
    ADD BX,15

    PUSH AX
    PUSH BX
    CALL CHECK_SOLID_TILE
    ADD SP,4

    CMP AL,1
    JNE .DONE

.LAND:
    MOV AX,[MARIO_Y]
    ADD AX,15
    SUB AX,8
    AND AX,0FFF0H
    ADD AX,8
    SUB AX,16

    MOV [MARIO_Y],AX
    MOV BYTE [MARIO_Y_FRAC],0
    MOV WORD [VELOCITY_Y],0
    MOV BYTE [ON_GROUND],1
    MOV BYTE [JUMP_HELDING],0
    JMP .DONE

.CHECK_UP:
    ; CHECK ABOVE MARIO
    MOV AX,[MARIO_X]
    INC AX
    MOV BX,[MARIO_Y]

    PUSH AX
    PUSH BX
    CALL CHECK_SOLID_TILE
    ADD SP,4

    CMP AL,1
    JE .HIT_HEAD

    MOV AX,[MARIO_X]
    ADD AX,14
    MOV BX,[MARIO_Y]

    PUSH AX
    PUSH BX
    CALL CHECK_SOLID_TILE
    ADD SP,4

    CMP AL,1
    JNE .DONE

.HIT_HEAD:
    MOV AX,[MARIO_Y]
    SUB AX,8
    AND AX,0FFF0H
    ADD AX,24

    MOV [MARIO_Y],AX
    MOV BYTE [MARIO_Y_FRAC],0
    MOV WORD [VELOCITY_Y],0

.DONE:
    POP BX
    POP AX
    RET


; CHECK MARIO LEVEL BOUNDARIES
CHECK_BOUNDARIES:
    PUSH AX

    ; CHECK LEFT SCREEN EDGE
    CMP WORD [MARIO_X], 0
    JG CHECK_RIGHT_BOUNDARY

    MOV WORD [MARIO_X], 0
    MOV BYTE [MARIO_X_FRAC], 0
    MOV WORD [VELOCITY_X], 0

CHECK_RIGHT_BOUNDARY:
    ; SCREEN WIDTH MINUS MARIO WIDTH
    MOV AX, SCREEN_WIDTH
    SUB AX, TILE_SIZE

    CMP WORD [MARIO_X], AX
    JL END_BOUNDARIES

    MOV [MARIO_X], AX
    MOV BYTE [MARIO_X_FRAC], 0
    MOV WORD [VELOCITY_X], 0

END_BOUNDARIES:
    POP AX
    RET

; UPDATE PLAYER MOVEMENT
UPDATE_PLAYER:
    PUSH AX
    ; CHECK IF MARIO IS ON THE GROUND
    CMP BYTE [ON_GROUND], 1
    JE GROUND_MOVEMENT
    ; MARIO IS IN THE AIR
    CALL AIR_CONTROL
    JMP END_PLAYER_MOVEMENT


GROUND_MOVEMENT:
    ; UPDATE HORIZONTAL MOVEMENT
    CALL UPDATE_HORIZONTAL


END_PLAYER_MOVEMENT:
    POP AX
    RET

; COMPLETE PLAYER UPDATE
UPDATE_PLAYER_FRAME:
    PUSH AX

    CALL START_JUMP
    CALL UPDATE_PLAYER
    CALL UPDATE_VERTICAL
    CALL UPDATE_POSITION

    ; HANDLE COLLISIONS
    CALL COLLIDE_VERTICAL
    CALL COLLIDE_HORIZONTAL

    ; CHECK SCREEN EDGES
    CALL CHECK_BOUNDARIES

    POP AX
    RET




    ; horizontal part 
        ; horizontal working
    UPDATE_HORIZONTAL: ; this function check whether moving left or right
    PUSH AX
    PUSH BX
    CMP BYTE [LEFT_KEY], 1 ; CHECK LEFT KEY
    JE MOVE_LEFT

    CMP BYTE [RIGHT_KEY], 1 ; CHECK RIGHT KEY
    JE MOVE_RIGHT
    
    JMP APPLY_FRICTION ; NO KEY PRESSED, APPLY FRICTION


MOVE_LEFT:
    MOV BYTE [FACING_DIRECTION], 0
    
    CMP WORD [VELOCITY_X], 0 ; CHECK IF MARIO WAS MOVING RIGHT
    JG BRAKE_RIGHT ;if moving right will add -ve accelearation

    MOV AX, [VELOCITY_X] ; if was alredy on the left so we ACCELERATE LEFT
    SUB AX, WALK_ACCEL
    MOV [VELOCITY_X], AX
    CALL CHECK_LEFT_LIMIT
    JMP END_HORIZONTAL



MOVE_RIGHT: ;this working same as above one jsut chaneged it for the right moevement
    MOV BYTE [FACING_DIRECTION], 1
    CMP WORD [VELOCITY_X], 0
    JL BRAKE_LEFT

    MOV AX, [VELOCITY_X]
    ADD AX, WALK_ACCEL
    MOV [VELOCITY_X], AX
    CALL CHECK_RIGHT_LIMIT
    JMP END_HORIZONTAL  

BRAKE_RIGHT: ; this function work when like we were moving right and we cliked left key THEN
             ; it will slow us down 
    MOV AX, [VELOCITY_X]
    SUB AX, BRAKE_ACCEL
    CMP AX, 0
    JG SAVE_BRAKE_RIGHT
    MOV AX, 0

SAVE_BRAKE_RIGHT:
    MOV [VELOCITY_X], AX
    JMP END_HORIZONTAL


BRAKE_LEFT: ;same like the above jsut doing for the left side
     MOV AX, [VELOCITY_X]
    ADD AX, BRAKE_ACCEL
    CMP AX, 0
    JL SAVE_BRAKE_LEFT
    MOV AX, 0

SAVE_BRAKE_LEFT:
    MOV [VELOCITY_X], AX
    JMP END_HORIZONTAL


APPLY_FRICTION: ; do i really have to explin this ? i am lazy to write this 
    MOV AX, [VELOCITY_X]
    CMP AX, 0
    JE END_HORIZONTAL
    JG FRICTION_RIGHT

    ; MARIO MOVING LEFT
    ADD AX, FRICTION

    CMP AX, 0
    JL SAVE_FRICTION

    MOV AX, 0
    JMP SAVE_FRICTION


FRICTION_RIGHT:

    ; MARIO MOVING RIGHT
    SUB AX, FRICTION

    CMP AX, 0
    JG SAVE_FRICTION

    MOV AX, 0


SAVE_FRICTION:

    MOV [VELOCITY_X], AX
    JMP END_HORIZONTAL


AIR_CONTROL: ;in air contorl

    PUSH AX
    PUSH BX
    CMP BYTE [LEFT_KEY], 1 ; CHECK LEFT KEY
    JE AIR_MOVE_LEFT
    CMP BYTE [RIGHT_KEY], 1 ; CHECK RIGHT KEY
    JE AIR_MOVE_RIGHT
    JMP END_AIR_CONTROL


AIR_MOVE_LEFT: ; 
    MOV BYTE [FACING_DIRECTION], 0
    CMP WORD [VELOCITY_X], 0 ; BRAKE IF MOVING RIGHT
    JG BRAKE_RIGHT

    MOV AX, [VELOCITY_X]  ; ACCELERATE LEFT
    SUB AX, WALK_ACCEL
    MOV [VELOCITY_X], AX
    CALL CHECK_LEFT_LIMIT
    JMP END_HORIZONTAL


AIR_MOVE_RIGHT: ;(same for above jsut for the right side)
    MOV BYTE [FACING_DIRECTION], 1
    CMP WORD [VELOCITY_X], 0
    JL BRAKE_LEFT

    MOV AX, [VELOCITY_X]
    ADD AX, WALK_ACCEL
    MOV [VELOCITY_X], AX
    CALL CHECK_RIGHT_LIMIT
    JMP END_AIR_CONTROL


END_AIR_CONTROL:
    POP BX
    POP AX
    RET

END_HORIZONTAL:
    POP BX
    POP AX
    RET